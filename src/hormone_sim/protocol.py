"""IRB-style study protocol skeleton generator.

Produces a complete, editable protocol draft for a clinician-supervised
dose-titration study of pharmacologic lactation induction in trans-feminine
adults — the design sketched in ``docs/briefing-metoclopramide.md``, expanded
to IRB-submission shape.

What is auto-filled from the model: the expected-values tables (population
bands at the starting and maximum doses, computed live) and the titration
schedule arithmetic. What is deliberately left as placeholders for the
site/principal investigator: names, IRB protocol numbers, local consent-form
references, co-investigators. A skeleton that pretends to be a finished
protocol would be worse than useless — the placeholders are the honest part.

Design summary (why this shape):
  * **Open-label dose-titration case series** — the cheapest design that
    yields individually meaningful data (each participant finds their own
    minimum effective dose) while accumulating the cohort that does not
    exist. Not an RCT; the comparison is each participant against the
    pre-registered model bands.
  * **Safety-first titration**: start low, prolactin-anchored step-ups,
    hard 12-week ceiling, AIMS monitoring extending past stop.
  * Every participant is consented including the specific off-label nature,
    the TD irreversibility asymmetry, and (if domperidone) the QT/not-FDA-
    approved status.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from .galactagogues import get_galactagogue, prolactin_response
from .lactation import LactationProtocol, simulate_lactation
from .sensitivity import simulate_lactation_population
from .progestogens import get_progestogen


@dataclass(frozen=True)
class ProtocolConfig:
    agent: str = "metoclopramide"
    start_dose_mg_day: float = 10.0
    max_dose_mg_day: float = 20.0
    target_prolactin_ng_ml: float = 70.0
    prep_weeks: float = 30.0
    progesterone_start_weeks: Optional[float] = None
    progesterone_dose_mg_day: float = 200.0
    pumping_sessions_per_day: float = 8.0
    duration_weeks: float = 12.0
    title: str = ("Low-dose, short-course D2-antagonist lactation induction "
                  "in trans-feminine adults: a prospective dose-titration "
                  "case series")
    site: str = "[SITE — clinic name, city]"
    pi: str = "[PRINCIPAL INVESTIGATOR]"
    version: str = "0.1-draft (generated by hormone-sim; every bracket is for the PI to fill)"


def _expected_values(cfg: ProtocolConfig) -> str:
    """Live model bands at the starting and max doses (the pre-registered
    expected-values table)."""
    rows = []
    for dose in (cfg.start_dose_mg_day, cfg.max_dose_mg_day):
        proto = LactationProtocol(
            galactagogue=cfg.agent, galactagogue_dose_mg_day=dose,
            prep_weeks=cfg.prep_weeks,
            progesterone_start_weeks=cfg.progesterone_start_weeks,
            progesterone_dose_mg_day=cfg.progesterone_dose_mg_day,
            pumping_sessions_per_day=cfg.pumping_sessions_per_day,
        )
        pop = simulate_lactation_population(proto, n=200, seed=42)
        p10, p50, p90 = pop.steady_state()
        g = get_galactagogue(cfg.agent)
        rows.append((dose, prolactin_response(g, dose), p10, p50, p90))
    lines = [
        "| Dose (mg/day) | Expected prolactin (ng/mL) | "
        "Supply p10 (mL/day) | Supply median | Supply p90 |",
        "|---|---|---|---|---|",
    ]
    for dose, prl, p10, p50, p90 in rows:
        lines.append(f"| {dose:g} | ~{prl:.0f} | {p10:.0f} | {p50:.0f} | {p90:.0f} |")
    lines.append("")
    lines.append("*Population-prior expected values, generated by hormone-sim "
                 "(`n=200` sampled parameter sets; drug-response and gland "
                 "uncertainty both included). These bands are pre-registered "
                 "as the comparison distribution for each participant's "
                 "trajectory; they are extrapolations from postpartum cis "
                 "literature, not predictions.*")
    return "\n".join(lines)


def generate_protocol(cfg: Optional[ProtocolConfig] = None) -> str:
    cfg = cfg or ProtocolConfig()
    g = get_galactagogue(cfg.agent)
    prog = get_progestogen("micronized_progesterone")
    p_start = (max(0.0, cfg.prep_weeks - 12.0) if cfg.progesterone_start_weeks
               is None else cfg.progesterone_start_weeks)

    approval = "FDA-approved (boxed warning: tardive dyskinesia)" if g.approved_us \
        else "NOT FDA-approved"

    return f"""# Study protocol: {cfg.title}

**Version:** {cfg.version}
**Site:** {cfg.site}
**Principal investigator:** {cfg.pi}
**Agent under study:** {cfg.agent} ({approval})

---

## 1. Background and rationale

Pharmacologic galactagogues (D2-receptor antagonists) are used off-label for
induced lactation, including by trans-feminine women (Newman–Goldfarb-style
protocols). The evidence base consists almost entirely of postpartum cis-female
studies and a single trans-feminine case report (Reisman & Goldstein, N Engl J
Med 2018;378). There are **no controlled trials and no dose-finding data** in
trans-feminine physiology, which differs materially: no pregnancy priming,
chronic exogenous estradiol, different baseline prolactin. Meanwhile mechanistic
modeling (hormone-sim, open source) predicts (a) an efficacy knee around
15–20 mg/day of {cfg.agent}, above which additional dose buys little supply
while tardive-dyskinesia exposure accumulates linearly, and (b) large
between-person heterogeneity at low doses — motivating titration-to-effect
rather than fixed dosing. This study collects the first prospective,
individually-titrated data in this population.

## 2. Specific aims

1. **Primary:** characterize the *minimum effective dose* of {cfg.agent}
   (prolactin-anchored: the lowest dose reaching each participant's target
   prolactin, target = {cfg.target_prolactin_ng_ml:.0f} ng/mL) when titrated
   from {cfg.start_dose_mg_day:g} mg/day in 5 mg/day steps (ceiling
   {cfg.max_dose_mg_day:g} mg/day).
2. **Secondary:** milk-supply trajectories versus pre-registered
   population-model bands; prolactin achieved per dose; adverse-event
   incidence (with emphasis on movement disorder screening via AIMS).
3. **Exploratory:** compare observed trajectories to the model posterior for
   each participant (personal-inference layer), to evaluate whether the
   population model is usable as a per-person titration aid.

## 3. Design

Prospective, open-label, single-arm dose-titration case series. Each
participant serves as their own control against the pre-registered model
bands. Sample size: {cfg.site == '[SITE — clinic name, city]' and '[TARGET N — e.g., 5–15; feasibility-driven case series]' or '[TARGET N]'}.

**Timeline per participant:**

1. **Preparation phase ({cfg.prep_weeks:g} weeks):** continue established
   GAHT (estradiol + anti-androgen); add micronized progesterone
   ({prog.typical_dose_mg_day:g} mg/day from week {p_start:g}) to complete
   glandular priming. No galactagogue during this phase.
2. **Transition ("the drop"):** abrupt discontinuation of estradiol and
   progesterone; galactagogue starts same day; pumping
   {cfg.pumping_sessions_per_day:g} sessions/day begins.
3. **Titration phase ({cfg.duration_weeks:g} weeks, hard ceiling):** start
   {cfg.start_dose_mg_day:g} mg/day; prolactin at week 2; step-up by 5 mg/day
   no more often than every 2 weeks if prolactin below target; once supply
   goal met, step DOWN to the minimum maintaining dose.
4. **Follow-up:** AIMS at 1 and 3 months post-stop.

## 4. Population

**Inclusion:** trans-feminine adults (≥18), on stable GAHT ≥ 6 months,
planning induced lactation, able to comply with monitoring schedule.

**Exclusion (screen):** pre-existing movement disorder or neuroleptic
exposure; concurrent dopamine-antagonist therapy; pregnancy/lactation;
history of {'' if g.approved_us else 'cardiac conduction disease / QT-prolonging medications (domperidone QT risk), '}major cardiac disease; uncontrolled mood disorder
(metoclopramide CNS effects); hepatic or renal impairment without
prescriber sign-off.

**{cfg.pi}** confirms eligibility per site practice.

## 5. Interventions and dosing

* Agent: {cfg.agent}. Regulatory status: {approval}.{" NOT approved for any use in the US; participants must be consented specifically on the QT-prolongation risk and the availability of approved alternatives." if not g.approved_us else " Off-label for lactation induction; boxed warning (tardive dyskinesia) reviewed in consent."}
* Dosing per §3; total exposure capped by the {cfg.duration_weeks:g}-week
  ceiling. No other dopamine antagonists permitted during the study.
* Prep-phase progesterone: micronized progesterone
  {cfg.progesterone_dose_mg_day:g} mg/day (weeks {p_start:g}–{cfg.prep_weeks:g}),
  discontinued at the drop.

## 6. Outcomes and measurement schedule

| Timepoint | Prolactin | AIMS | Milk log | Adverse events |
|---|---|---|---|---|
| Baseline (pre-drop) | ✓ | ✓ | — | ✓ |
| Week 2 | ✓ | ✓ | daily diary | ✓ |
| Every 2–4 wk during | ✓ | ✓ | daily diary | ✓ |
| End of titration | ✓ | ✓ | daily diary | ✓ |
| Post-stop 1 & 3 mo | — | ✓ | — | ✓ |

Milk volumes recorded in mL/day (community oz logs converted at ingest;
1 fl oz = 29.5735 mL). Data instruments: participant CSV log
(date/drop-date/weeks-post-drop/dose/prolactin/milk/notes) and the AIMS
record module.

## 7. Expected values (pre-registered model bands)

{_expected_values(cfg)}

## 8. Safety and stopping rules

* **Hard ceiling:** {cfg.duration_weeks:g} weeks total galactagogue exposure;
  no extensions.
* **AIMS flags** (any item ≥ 3; any item ≥ 2 above baseline; total ≥ 3 above
  baseline) → pause dose changes and reassess with prescriber within 48 h;
  suspected TD → stop the drug and refer for neurology evaluation. Flags are
  safety signals, not diagnoses.
* **Prolactin** persistently above [SITE: define, e.g., >200 ng/mL] → hold
  and reassess.
* Participant may stop at any time for any reason; post-stop monitoring
  continues per §6.

## 9. Statistical plan

Descriptive case-series statistics; per-participant dose–prolactin curves;
supply trajectories plotted against the §7 bands (and, secondarily, against
each participant's own posterior from the personal-inference layer, with
effective-sample-size diagnostics). No hypothesis tests of efficacy are
powered for at feasible n; the study's purpose is dose-finding and
signal-generation, and it says so.

## 10. Ethics and consent

* IRB/REC review required before any participant is enrolled
  ([IRB PROTOCOL NUMBER]).
* Consent must state specifically: off-label use{'; non-FDA-approved agent' if not g.approved_us else ''};
  the tardive-dyskinesia risk profile (cumulative, potentially irreversible,
  no biomarker — monitored by clinical exam, can emerge after stopping);
  the experimental nature of dosing in this population; that the hormone
  drop is temporary and its course planned; the right to withdraw at any
  time with clinical care unaffected.
* Data privacy: participant logs are identifiable health data; store per
  site policy, report de-identified aggregates publicly.
* Community dissemination: results (including null and adverse results)
  published open-access and shared with community organizations.

## 11. References

1. Reisman T, Goldstein Z. Induced lactation in a transgender woman. N Engl J Med. 2018;378.
2. Grimley et al. Endocrine treatment of gender-dysphoria/gender-incongruent persons. J Clin Endocrinol Metab. 2017;102(11).
3. WPATH. Standards of Care, Version 8. 2022.
4. FDA. Metoclopramide labeling (boxed warning; 12-week guidance).
5. OSHERC. Domperidone for lactation. 2018.
6. hormone-sim repository: model, parameters, and provenance (docs/references.md).

---

*Generated by hormone-sim `protocol` — a skeleton for the PI to complete, not
an approved protocol. Every bracketed field requires site-specific input.*
"""
